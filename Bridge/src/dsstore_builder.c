typedef struct {
    uint32_t fn_len;
    const char* fn;
    const char* type_code;
    const char* data_type;
    uint8_t* data;
    uint32_t data_len;
} record_t;

// Hardcoded sort order (., then icons alphabetically)
static int cmp_records(const void* a, const void* b) {
    const record_t* ra = (const record_t*)a;
    const record_t* rb = (const record_t*)b;
    if (ra->fn_len != rb->fn_len) return ra->fn_len - rb->fn_len;
    int c = strcmp(ra->fn, rb->fn);
    if (c != 0) return c;
    return strncmp(ra->type_code, rb->type_code, 4);
}

static void write_record(uint8_t** p, const record_t* r) {
    w32(p, r->fn_len);
    w_str(p, r->fn);
    memcpy(*p, r->type_code, 4); *p += 4;
    memcpy(*p, r->data_type, 4); *p += 4;
    if (strcmp(r->data_type, "blob") == 0) {
        w32(p, r->data_len);
    }
    memcpy(*p, r->data, r->data_len); *p += r->data_len;
}

uint8_t* dsstore_build(const dsstore_config_t* config, size_t* out_size) {
    uint8_t* buf = (uint8_t*)calloc(1, MAX_DSSTORE_SIZE);
    if (!buf) return NULL;

    record_t records[64];
    size_t num_records = 0;

    // BKGD
    uint8_t bkgd_data[12] = {'P','c','t','B',0,0,0,0, 0,0,0,0};
    if (config->background_image_path) {
        // minimal fake alias for BKGD, length 64
        // real alias is complex, but Finder doesn't strictly reject it if we put some dummy size, 
        // actually for simplicity we just put a dummy data
        uint32_t alias_size = 64;
        bkgd_data[4] = (alias_size >> 24) & 0xFF;
        bkgd_data[5] = (alias_size >> 16) & 0xFF;
        bkgd_data[6] = (alias_size >> 8) & 0xFF;
        bkgd_data[7] = alias_size & 0xFF;
    }
    records[num_records++] = (record_t){1, ".", "BKGD", "blob", bkgd_data, 12};

    // bwsp
    uint8_t bwsp_data[sizeof(bwsp_tpl)];
    memcpy(bwsp_data, bwsp_tpl, sizeof(bwsp_tpl));
    // string {{0, 0}, {400, 300}} is at offset 138 in template, length 20
    // we can replace it with padded string if needed, but we keep it static for simplicity
    records[num_records++] = (record_t){1, ".", "bwsp", "blob", bwsp_data, sizeof(bwsp_data)};

    // icvo
    uint8_t icvo_data[sizeof(icvo_tpl)];
    memcpy(icvo_data, icvo_tpl, sizeof(icvo_tpl));
    records[num_records++] = (record_t){1, ".", "icvo", "blob", icvo_data, sizeof(icvo_data)};

    // Iloc for icons
    uint8_t** iloc_data = (uint8_t**)calloc(config->icon_count, sizeof(uint8_t*));
    for (size_t i = 0; i < config->icon_count; i++) {
        iloc_data[i] = (uint8_t*)malloc(16);
        uint8_t* p = iloc_data[i];
        w32(&p, config->icons[i].pos.x);
        w32(&p, config->icons[i].pos.y);
        w32(&p, 0xFFFF);
        w32(&p, 0xFFFF);
        records[num_records++] = (record_t){
            (uint32_t)strlen(config->icons[i].filename),
            config->icons[i].filename,
            "Iloc", "blob", iloc_data[i], 16
        };
    }

    qsort(records, num_records, sizeof(record_t), cmp_records);

    uint8_t* wp = buf;
    
    // Header
    w32(&wp, 1);
    w32(&wp, 0x42756431);
    w32(&wp, 32 + 32 + 4096);
    uint32_t alloc_size_offset = (uint32_t)(wp - buf);
    w32(&wp, 0); // placeholder
    w32(&wp, 32 + 32 + 4096);
    wp += 12; // pad 12

    // DSDB Master Block
    w32(&wp, 1); // root block id
    w32(&wp, 1); // levels
    w32(&wp, num_records);
    w32(&wp, 1); // nodes
    w32(&wp, 1); // is leaf
    wp += 12; // pad to 32

    // Root Block (Block 1)
    uint8_t* root_start = wp;
    w32(&wp, 0); // next node
    w32(&wp, num_records);
    for (size_t i = 0; i < num_records; i++) {
        write_record(&wp, &records[i]);
    }
    wp = root_start + 4096;

    // Allocator Info
    uint8_t* alloc_start = wp;
    w32(&wp, 2); // num blocks
    w32(&wp, 0);
    
    w32(&wp, 32); // Block 0 offset
    w32(&wp, 64); // Block 1 offset
    for (int i = 2; i < 256; i++) w32(&wp, 0);
    for (int i = 0; i < 32; i++) w32(&wp, 0); // free lists
    w32(&wp, 1); // num TOC entries
    *wp++ = 4; // name len
    memcpy(wp, "DSDB", 4); wp += 4;
    w32(&wp, 0); // block 0

    uint32_t alloc_size = (uint32_t)(wp - alloc_start);
    uint8_t* ptr = buf + alloc_size_offset;
    w32(&ptr, alloc_size);

    *out_size = (size_t)(wp - buf);
    
    for (size_t i = 0; i < config->icon_count; i++) {
        free(iloc_data[i]);
    }
    free(iloc_data);

    return buf;
}
