#define MAX_DSSTORE_SIZE 32768

static void w32(uint8_t** p, uint32_t val) {
    (*p)[0] = (val >> 24) & 0xFF;
    (*p)[1] = (val >> 16) & 0xFF;
    (*p)[2] = (val >> 8) & 0xFF;
    (*p)[3] = val & 0xFF;
    *p += 4;
}

static void w16(uint8_t** p, uint16_t val) {
    (*p)[0] = (val >> 8) & 0xFF;
    (*p)[1] = val & 0xFF;
    *p += 2;
}

static void w_str(uint8_t** p, const char* str) {
    while (*str) {
        w16(p, (uint16_t)(*str));
        str++;
    }
}

